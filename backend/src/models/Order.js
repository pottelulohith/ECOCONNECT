import mongoose from 'mongoose';

const orderSchema = new mongoose.Schema(
  {
    orderId: {
      type: String,
      required: true,
      unique: true,
      index: true,
    },
    purchaseRequestId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'PurchaseRequest',
      default: null,
    },
    industryId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    polymer: {
      type: String,
      required: true,
    },
    quantityKg: {
      type: Number,
      required: true,
    },
    totalAmount: {
      type: Number,
      default: 0,
    },
    status: {
      type: String,
      enum: [
        'Processing',
        'Approved',
        'Truck Dispatched',
        'Loading OTP Verified',
        'In Transit',
        'Delivered',
        'Cancelled',
      ],
      default: 'Processing',
    },
    eta: {
      type: String,
      default: '',
    },
    destination: {
      type: String,
      default: '',
    },

    // ─── Driver & Truck (editable by Industry) ────────────────────
    vehicleNo: {
      type: String,
      default: '',
    },
    driverName: {
      type: String,
      default: '',
    },
    driverPhone: {
      type: String,
      default: '',
    },
    driverUpdatedAt: {
      type: Date,
      default: null,
    },

    // ─── Trip Status Tracking ─────────────────────────────────────
    trip1: {
      label: { type: String, default: 'Industry → Municipality' },
      status: {
        type: String,
        enum: ['Pending', 'In Transit', 'Arrived', 'Completed'],
        default: 'Pending',
      },
      startedAt: { type: Date, default: null },
      completedAt: { type: Date, default: null },
    },
    trip2: {
      label: { type: String, default: 'Municipality → Industry' },
      status: {
        type: String,
        enum: ['Pending', 'In Transit', 'Arrived', 'Completed'],
        default: 'Pending',
      },
      startedAt: { type: Date, default: null },
      completedAt: { type: Date, default: null },
    },

    // ─── 5-Step Progress Tracking ─────────────────────────────────
    progressSteps: [
      {
        step: { type: Number, required: true }, // 1-5
        label: { type: String, required: true },
        completed: { type: Boolean, default: false },
        current: { type: Boolean, default: false },
        completedAt: { type: Date, default: null },
      },
    ],

    // ─── Loading OTP (generated by Industry, verified by Municipality) ─
    loadingOtp: {
      otpHash: { type: String, default: null },
      otpPlain: { type: String, default: null }, // shown to industry only (or use hash-only)
      expiresAt: { type: Date, default: null },
      attempts: { type: Number, default: 0 },
      maxAttempts: { type: Number, default: 5 },
      verified: { type: Boolean, default: false },
      verifiedAt: { type: Date, default: null },
      verifiedBy: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        default: null,
      },
      generatedAt: { type: Date, default: null },
    },

    // ─── Actual Loaded Weight (entered by Municipality during loading) ─
    actualLoadedKg: {
      type: Number,
      default: null,
    },

    // ─── Delivery OTP (separate from loading OTP) ─────────────────
    deliveryOtp: {
      otpHash: { type: String, default: null },
      otpPlain: { type: String, default: null },
      expiresAt: { type: Date, default: null },
      attempts: { type: Number, default: 0 },
      maxAttempts: { type: Number, default: 5 },
      verified: { type: Boolean, default: false },
      verifiedAt: { type: Date, default: null },
      verifiedBy: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        default: null,
      },
      generatedAt: { type: Date, default: null },
    },

    // ─── Delivery & Quantity Reconciliation ────────────────────────
    actualDeliveredKg: {
      type: Number,
      default: null,
    },
    reconciliation: {
      weightDiffKg: { type: Number, default: null },
      notes: { type: String, default: '' },
      reconciledAt: { type: Date, default: null },
    },

    // ─── Timeline Events (audit trail) ────────────────────────────
    timeline: [
      {
        event: { type: String, required: true },
        description: { type: String, default: '' },
        timestamp: { type: Date, default: Date.now },
        actor: { type: String, default: '' },
        actorRole: { type: String, default: '' },
      },
    ],

    // Legacy fields (kept for backward compat)
    currentLocation: {
      type: String,
      default: '',
    },
    coords: {
      lat: { type: Number, default: null },
      lng: { type: Number, default: null },
    },
    milestones: [
      {
        step: { type: String },
        time: { type: String },
        completed: { type: Boolean, default: false },
        current: { type: Boolean, default: false },
      },
    ],
  },
  {
    timestamps: true,
  }
);

export const Order = mongoose.model('Order', orderSchema);
